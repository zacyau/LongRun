"""
应用配置模块

本模块定义应用程序的所有配置项，支持：
1. 从环境变量读取配置
2. 从.env文件读取配置
3. 提供默认值

配置项包括：
- 应用基本信息（名称、调试模式、主机端口）
- 数据库连接
- 缓存设置
- 定时任务执行时间
- CORS跨域配置
"""

from pydantic_settings import BaseSettings
from functools import lru_cache


class Settings(BaseSettings):
    """
    应用配置类

    使用Pydantic的BaseSettings实现自动配置加载，
    配置项可通过环境变量或.env文件覆盖默认值。

    配置项说明：
    """

    # -----------------------------------------------------------------------------
    # 应用基本信息
    # -----------------------------------------------------------------------------
    # 应用名称
    app_name: str = "Long Run"

    # 调试模式，True时启用热重载等开发功能
    debug: bool = True

    # 服务器监听地址，0.0.0.0表示接受所有网络接口的连接
    host: str = "0.0.0.0"

    # 服务器端口号
    port: int = 8000

    # -----------------------------------------------------------------------------
    # 数据库与缓存配置
    # -----------------------------------------------------------------------------
    # 数据库连接URL，支持SQLite和PostgreSQL等
    # SQLite示例: sqlite:///./long_run_data.db
    database_url: str = "sqlite:///./long_run_data.db"

    # 缓存数据过期时间（小时）
    # 超过此时间的数据将被视为过期，需要重新获取
    cache_ttl_hours: int = 24

    # -----------------------------------------------------------------------------
    # 定时任务配置
    # -----------------------------------------------------------------------------
    # 数据更新的小时（24小时制）
    # A股收盘时间为15:00，建议设置为16:00-20:00之间
    data_update_hour: int = 20

    # 数据更新的分钟
    data_update_minute: int = 0

    # -----------------------------------------------------------------------------
    # CORS跨域配置
    # -----------------------------------------------------------------------------
    # 允许跨域请求的来源列表
    # 开发环境通常为localhost，生产环境需要配置实际域名
    cors_origins: list[str] = ["http://localhost:5173", "http://127.0.0.1:5173"]

    class Config:
        # 指定环境变量前缀，读取时自动转换
        # 例如：APP_NAME -> app_name
        env_file = ".env"


@lru_cache()
def get_settings() -> Settings:
    """
    获取配置单例

    使用@lru_cache装饰器确保整个应用生命周期内
    只创建一次Settings实例，避免重复读取配置。

    返回:
        Settings: 应用配置实例

    注意:
        - 该函数会被多次调用，但只会创建一个Settings实例
        - 如果需要重新加载配置，需要重启应用
    """
    return Settings()
